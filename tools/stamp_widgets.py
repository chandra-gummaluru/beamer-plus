#!/usr/bin/env python3
"""Make every widget in widgets/ self-contained.

A widget has to work when it is opened on its own — a file double-clicked in
a browser, sent to a colleague, dropped in a deck — not only inside Beamer+.
So each one carries its own copy of the two things Beamer+ otherwise injects:

    static/css/widget-base.css       the shared look (tokens, bar, buttons)
    static/js/widget-settings-kit.js the bar, Edit / Done, edit mode, scale …

This script copies the current versions of both into every widget, between
the markers below, replacing whatever copy was there. Edit those two files,
never the copies, then run:

    python tools/stamp_widgets.py          # rewrite the widgets
    python tools/stamp_widgets.py --check  # exit 1 if any widget is stale

Inside Beamer+ the host still injects its own copies first; the kit guards
against running twice, and the identical stylesheet simply repeats.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WIDGETS = ROOT / 'widgets'
BASE_CSS = ROOT / 'static' / 'css' / 'widget-base.css'
KIT_JS = ROOT / 'static' / 'js' / 'widget-settings-kit.js'

BEGIN = '<!-- bw-kit:begin'
END = '<!-- bw-kit:end -->'

FONTS = ('<link rel="preconnect" href="https://fonts.googleapis.com">\n'
         '<link href="https://fonts.googleapis.com/css2?family=JetBrains+Mono:ital,wght@0,400;0,500;1,400'
         '&family=DM+Sans:wght@400;500;600&display=swap" rel="stylesheet">')

# The older fallback that linked ../static/css/widget-base.css (and so only
# worked from inside the repo). Its comment comes with it.
OLD_STANDALONE = re.compile(
    r'(?:<!--(?:(?!-->).)*?Standalone fallback.*?-->\s*)?'
    r'<script id="bw-standalone">.*?</script>\s*', re.S)
STAMP = re.compile(r'\n?' + re.escape(BEGIN) + r'.*?' + re.escape(END) + r'[ \t]*\r?\n?', re.S)
CHARSET = re.compile(r'[ \t]*<meta charset="[^"]*">[ \t]*\r?\n?', re.I)
TITLE_END = re.compile(r'</title>[ \t]*\r?\n?', re.I)


def _inline(text: str) -> str:
    # Nothing inside may close the element early.
    return text.replace('</style', '<\\/style').replace('</script', '<\\/script').rstrip() + '\n'


def stamp_block() -> str:
    css = BASE_CSS.read_text(encoding='utf-8')
    js = KIT_JS.read_text(encoding='utf-8')
    return (f'{BEGIN} — generated by tools/stamp_widgets.py from static/css/widget-base.css\n'
            '     and static/js/widget-settings-kit.js, so this file works opened on its own.\n'
            '     Edit those two files and re-run the script; changes made here are overwritten. -->\n'
            f'{FONTS}\n'
            f'<style id="bw-base">\n{_inline(css)}</style>\n'
            f'<script id="bw-kit">\n{_inline(js)}</script>\n'
            f'{END}\n')


def stamped(html: str, block: str) -> str:
    out = STAMP.sub('', html)
    out = OLD_STANDALONE.sub('', out)
    # The charset first in <head>: the stamp is long, and a browser only looks
    # for it in the first 1024 bytes of a file opened from disk.
    m = CHARSET.search(out)
    charset = m.group(0).strip() if m else '<meta charset="UTF-8">'
    if m:
        out = out[:m.start()] + out[m.end():]
    out = re.sub(r'(<head[^>]*>)[ \t]*\r?\n?', lambda h: f'{h.group(1)}\n{charset}\n', out, count=1, flags=re.I)
    # Straight after <title>: ahead of the widget's own <style>, so its rules
    # still win, and ahead of its script, which may use BeamerWidget at once.
    t = TITLE_END.search(out)
    if not t:
        raise ValueError('no </title>')
    return out[:t.end()] + '\n' + block + out[t.end():]


def main(argv: list[str]) -> int:
    check = '--check' in argv
    block = stamp_block()
    stale = []
    for path in sorted(WIDGETS.glob('*.html')):
        raw = path.read_bytes().decode('utf-8')
        crlf = '\r\n' in raw
        html = raw.replace('\r\n', '\n')
        new = stamped(html, block)
        if crlf:
            new = new.replace('\n', '\r\n')
        if new != raw:
            stale.append(path.name)
            if not check:
                path.write_bytes(new.encode('utf-8'))
    if check:
        if stale:
            print('Stale widget copies (run python tools/stamp_widgets.py):', ', '.join(stale))
            return 1
        print('All widgets are up to date.')
        return 0
    print(f'Stamped {len(stale)} widget(s)' + (': ' + ', '.join(stale) if stale else ''))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
